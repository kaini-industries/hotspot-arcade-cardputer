#!/usr/bin/env node
import { existsSync, readFileSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { basename, join, resolve } from 'node:path';

const directory = resolve(process.argv[2] ?? 'build');
const app = join(directory, 'hotspot-arcade-cardputer.ino.bin');
const partitions = join(directory, 'hotspot-arcade-cardputer.ino.partitions.bin');
const bootloader = join(directory, 'hotspot-arcade-cardputer.ino.bootloader.bin');
const elf = join(directory, 'hotspot-arcade-cardputer.ino.elf');
for (const path of [app, partitions, bootloader, elf]) {
  if (!existsSync(path) || statSync(path).size === 0) throw new Error(`missing nonempty build output ${basename(path)}`);
}
const appSlot = 0x330000;
const minimumHeadroom = 300 * 1024;
const appSize = statSync(app).size;
const headroom = appSlot - appSize;
if (headroom < minimumHeadroom) {
  throw new Error(`application image has ${headroom} bytes headroom; requires at least ${minimumHeadroom}`);
}

// The default_8MB partition binary is generated by the locked core. Validate its
// SHA-independent structural boundaries here; package validation later checks all
// image offsets and metadata with locked esptool.
const partitionBytes = readFileSync(partitions);
if (partitionBytes.length > 0x1000) throw new Error('partition table exceeds its 0x1000-byte flash region');

const root = resolve(import.meta.dirname, '..');
const lock = JSON.parse(readFileSync(join(root, 'tools', 'toolchain.lock.json'), 'utf8'));
const compiler = lock.arduino.coreTools.find((entry) => entry.name === 'esp-x32');
if (!compiler) throw new Error('toolchain lock has no esp-x32 compiler entry');
// Reproducibility jobs share one bootstrapped Arduino data directory with fresh
// detached worktrees. Honor the same documented Arduino CLI environment override
// used by compile instead of assuming every worktree has its own ignored cache.
const arduinoData = process.env.ARDUINO_DIRECTORIES_DATA
  ? resolve(process.env.ARDUINO_DIRECTORIES_DATA)
  : join(root, '.cache', 'arduino', 'data');
const sizeTool = join(
  arduinoData,
  'packages',
  'esp32',
  'tools',
  'esp-x32',
  compiler.version,
  'bin',
  'xtensa-esp32s3-elf-size',
);
if (!existsSync(sizeTool)) throw new Error(`locked ELF size tool is missing: ${sizeTool}`);
const sections = execFileSync(sizeTool, ['-A', elf], { encoding: 'utf8' });
const sectionSize = (name) => {
  const line = sections.split('\n').find((candidate) => candidate.trimStart().startsWith(`${name} `));
  if (!line) throw new Error(`ELF section ${name} is missing`);
  const fields = line.trim().split(/\s+/);
  const value = Number(fields[1]);
  if (!Number.isSafeInteger(value) || value < 0) throw new Error(`invalid ${name} size`);
  return value;
};
const staticDram = sectionSize('.dram0.data') + sectionSize('.dram0.bss');
const staticDramLimit = 90 * 1024;
if (staticDram > staticDramLimit) {
  throw new Error(`static DRAM is ${staticDram} bytes; limit is ${staticDramLimit}`);
}

console.log(
  `application ${appSize} bytes; partition headroom ${headroom} bytes; static DRAM ${staticDram} bytes`,
);
